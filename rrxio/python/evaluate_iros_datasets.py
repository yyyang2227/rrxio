def _git_rev(path):
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=path, stderr=subprocess.STDOUT).decode("utf-8").strip()
    except Exception:
        return "unknown"


def _ensure_dir(path):
    if not os.path.isdir(path):
        os.makedirs(path)


def _csv_column_count(line):
    return line.count(",") + 1


def _sanitize_csv_tail(path):
    if not os.path.isfile(path):
        return 0

    with open(path, "r", encoding="utf-8") as f:
        lines = [line.rstrip("\r\n") for line in f]

    if len(lines) <= 1:
        return 0

    expected_cols = _csv_column_count(lines[0])
    removed = 0
    while len(lines) > 1 and _csv_column_count(lines[-1]) != expected_cols:
        lines.pop()
        removed += 1

    if removed == 0:
        return 0

    with open(path, "w", encoding="utf-8") as f:
        for line in lines:
            f.write(line + "\n")
    return removed


def _append_manifest_row(manifest_csv, row):
    header = [
        "run_id", "date", "week", "stage", "dataset", "modality", "launch_file", "config_info", "camera_config",
        "bag_start", "bag_duration", "timeshift_cam_imu", "topic_radar_trigger", "topic_radar_scan", "feature_num",
        "git_rev_root", "git_rev_reve", "cov_mode", "scheduler_mode", "config_tag", "dvc_unified_config_file",
        "status", "owner", "note",
        "runtime_s", "export_directory", "diag_file", "sched_diag_file", "perf_mode_requested", "perf_mode_effective",
        "dvc_scheduler_max_events", "dvc_scheduler_backpressure_depth", "dvc_scheduler_backpressure_high",
        "dvc_scheduler_backpressure_low", "dvc_scheduler_backpressure_timeout_s", "dvc_scheduler_imu_fast_path"
    ]
    is_new = not os.path.isfile(manifest_csv)
    with open(manifest_csv, "a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=header)
        if is_new:
            writer.writeheader()
        writer.writerow(row)


def _yaml_quote(value):
    text = str(value)
    return "'" + text.replace("'", "''") + "'"


def _yaml_bool(value):
    return "true" if bool(value) else "false"


